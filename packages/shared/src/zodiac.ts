const BY_KEY: Record<ZodiacKey, ZodiacSign> = Object.fromEntries(
  ZODIAC_SIGNS.map(s => [s.key, s])
) as Record<ZodiacKey, ZodiacSign>;

/** Знак по ключу. */
export function zodiacByKey(key: string): ZodiacSign | null {
  return (BY_KEY as Record<string, ZodiacSign | undefined>)[key] ?? null;
}

/** Знак по году (упрощённо, без границы Нового года). */
export function signByYear(year: number): ZodiacSign {
  const idx = (((year - 4) % 12) + 12) % 12;
  return BY_KEY[ZODIAC_ORDER[idx] ?? 'rat'];
}

/** Стихия года (BaZi) по последней цифре. */
export function elementByYear(year: number): ElementName {
  return YEAR_ELEMENTS[((year % 10) + 10) % 10] ?? 'Дерево';
}

/** Знак по дате с учётом границы китайского Нового года (если дата известна). */
export function signByDate(day: number, month: number, year: number): ZodiacSign {
  const ny = NEW_YEAR_DATES[year];
  let effectiveYear = year;
  if (ny) {
    const [nyMonth, nyDay] = ny.split('-').map(Number);
    if (month < (nyMonth ?? 1) || (month === nyMonth && day < (nyDay ?? 1))) {
      effectiveYear = year - 1;
    }
  }
  return signByYear(effectiveYear);
}

export type CompatLevel = 'excellent' | 'good' | 'neutral' | 'challenging' | 'conflict';

export interface CompatResult {
  level: CompatLevel;
  label: string;
  text: string;
}

function inPair(
  pairs: readonly (readonly [ZodiacKey, ZodiacKey])[],
  a: ZodiacKey,
  b: ZodiacKey
): boolean {
  return pairs.some(([x, y]) => (x === a && y === b) || (x === b && y === a));
}

/** Совместимость двух знаков по системам Сань Хэ / Лю Хэ / Лю Чун + матрицам знаков. */
export function compatibility(a: ZodiacKey, b: ZodiacKey): CompatResult {
  const signA = BY_KEY[a];
  const signB = BY_KEY[b];
  if (inPair(ZODIAC_BEST_PAIRS, a, b)) {
    return {
      level: 'excellent',
      label: 'Идеальная пара (Лю Хэ)',
      text: `${signA.ru} и ${signB.ru} образуют одну из шести идеальных пар китайского зодиака — гармоничный союз в любви и делах.`,
    };
  }
  if (a !== b && ZODIAC_TRIADS.some(t => t.includes(a) && t.includes(b))) {
    return {
      level: 'excellent',
      label: 'Тройка гармонии (Сань Хэ)',
      text: `${signA.ru} и ${signB.ru} принадлежат одной тройке гармонии — глубокое взаимопонимание и поддержка на энергетическом уровне.`,
    };
  }
  if (inPair(ZODIAC_CONFLICT_PAIRS, a, b)) {
    return {
      level: 'conflict',
      label: 'Конфликт (Лю Чун)',
      text: `${signA.ru} и ${signB.ru} — пара прямого противостояния. Союз потребует терпения, уважения границ и компромиссов.`,
    };
  }
  if (signA.best.includes(b)) {
    return {
      level: 'good',
      label: 'Хорошая совместимость',
      text: `${signA.ru} и ${signB.ru} хорошо дополняют друг друга и легко находят общий язык.`,
    };
  }
  if (signA.worst.includes(b)) {
    return {
      level: 'challenging',
      label: 'Непростая совместимость',
      text: `${signA.ru} и ${signB.ru} различаются по темпераменту — отношения потребуют работы и взаимных уступок.`,
    };
  }
  return {
    level: 'neutral',
    label: 'Нейтральная совместимость',
    text: `${signA.ru} и ${signB.ru} — нейтральное сочетание: всё зависит от взаимного уважения и общих целей.`,
  };
}


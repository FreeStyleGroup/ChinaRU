export interface ChineseZodiacSign {
  key: string;
  ru: string;
  emoji: string;
  element: string;
  traits: string;
}

/** Знак по дате 'YYYY-MM-DD' либо null. Стихия — по году (BaZi). */
export function chineseZodiac(birthday: string | null | undefined): ChineseZodiacSign | null {
  if (!birthday) return null;
  const year = Number.parseInt(birthday.slice(0, 4), 10);
  if (!Number.isFinite(year) || year < 1900 || year > 2200) return null;
  const sign = signByYear(year);
  return {
    key: sign.key,
    ru: sign.ru,
    emoji: sign.emoji,
    element: elementByYear(year),
    traits: sign.short,
  };
}
